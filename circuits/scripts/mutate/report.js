"use strict";
// JSON + markdown rendering of a mutation run.
const fs = require("fs");
const path = require("path");

const cell = (s) => String(s == null ? "" : s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const code = (s) => (s ? "`" + cell(s) + "`" : "");

function toMarkdown(r) {
  const s = r.summary;
  const lines = [];
  lines.push(`# Mutation report — ${r.title}`);
  lines.push("");
  lines.push("Generated by `circuits/scripts/mutate.js` (G1-S1-CIRC-036, floor 1). Each constraint");
  lines.push("site is mutated (M1: `===` deleted, `<==`/`==>` weakened to `<--`/`-->`) and the spec is");
  lines.push("run against the mutant; a mutant must be KILLED by a failing test.");
  lines.push("");
  lines.push(`- Command: \`${r.command}\``);
  lines.push(`- Targets: ${r.targets.map((t) => "`" + t + "`").join(", ")}`);
  lines.push(`- Specs: ${r.specs.map((t) => "`" + t + "`").join(", ")}`);
  if (r.grep) lines.push(`- Tests run (\`--grep\`): ${code(r.grep)}`);
  if (r.forbidKillers) {
    lines.push(
      `- Forbidden killers (\`--forbid-killers\`): ${code(r.forbidKillers)}. A mutant whose only failing ` +
        "tests match this pattern counts as SURVIVED: such tests (static source text, constraint " +
        "counts, setup hooks) fail on any change without exercising soundness."
    );
  }
  lines.push(`- Compiler: ${r.circom}`);
  lines.push(`- Baseline (unmutated) run: ${r.baseline.passed ? `pass (${r.baseline.passes} tests)` : "FAIL"}`);
  lines.push(
    `- Result: **${s.total} mutants — ${s.killed} killed, ${s.survived} survived, ` +
      `${s.compile_error} compile errors, ${s.equivalent || 0} documented equivalent, ${s.timeout} timeouts, ` +
      `${s.error} errors** ` +
      `(mutation score ${s.score})`
  );
  lines.push("");
  lines.push("| Site | File:line | Template | Context | Original | Mutant | Outcome | Killed by |");
  lines.push("|---|---|---|---|---|---|---|---|");
  for (const m of r.mutants) {
    const outcome = m.outcome === "survived" ? "**SURVIVED**" : m.outcome;
    let first = m.killer || m.firstFailure;
    if (m.outcome === "compile_error") first = `${m.firstFailure} — ${m.detail || ""}`;
    else if (!first && m.forbiddenKillers) first = `(forbidden only: ${m.forbiddenKillers.join("; ")})`;
    else if (!first && m.detail) first = `(${m.detail})`;
    lines.push(
      `| ${m.id} | ${cell(m.file)}:${m.line} | ${cell(m.template || "-")} | ${cell(m.context || "-")} | ${code(m.original)} | ${code(m.mutant)} | ${outcome} | ${cell(first)} |`
    );
  }
  lines.push("");
  const tally = {};
  for (const m of r.mutants) if (m.outcome === "killed") tally[m.killer || m.firstFailure] = (tally[m.killer || m.firstFailure] || 0) + 1;
  const ks = Object.entries(tally).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
  if (ks.length) {
    lines.push("## Kills per test");
    lines.push("");
    lines.push("| Mutants killed | Test |");
    lines.push("|---|---|");
    for (const [t, n] of ks) lines.push(`| ${n} | ${cell(t)} |`);
    lines.push("");
  }
  const noted = r.mutants.filter((m) => m.note);
  if (noted.length) {
    lines.push("## Annotated mutants");
    lines.push("");
    lines.push("An `equivalent` outcome is a mutant that admits no new witness (proved in the note); it is");
    lines.push("documented instead of claimed as a kill. Other notes record redundancy in the composed");
    lines.push("circuit for a mutant that IS killed (by the component's own test).");
    lines.push("");
    lines.push("| Site | File:line | Original | Outcome | Note |");
    lines.push("|---|---|---|---|---|");
    for (const m of noted) lines.push(`| ${m.id} | ${cell(m.file)}:${m.line} | ${code(m.original)} | ${m.outcome} | ${cell(m.note)} |`);
    lines.push("");
  }
  if (s.survived > 0) {
    lines.push("Survivors are fixed (add a witness-level tamper test, circuits/scripts/MUTATION.md), not waived.");
    lines.push("");
  }
  if (s.compile_error > 0) {
    lines.push("Compile errors mean circom rejected the mutant (e.g. `<--` on an anonymous component);");
    lines.push("they remove nothing from a valid circuit but prove nothing about the tests either.");
    lines.push("");
  }
  return lines.join("\n");
}

/** Write `<stem>.md` and `<stem>.json` for a report path given with or without extension. */
function writeReport(report, reportPath) {
  const stem = reportPath.replace(/\.(md|json)$/, "");
  fs.mkdirSync(path.dirname(stem), { recursive: true });
  fs.writeFileSync(stem + ".json", JSON.stringify(report, null, 2) + "\n");
  fs.writeFileSync(stem + ".md", toMarkdown(report) + "\n");
  return { md: stem + ".md", json: stem + ".json" };
}

module.exports = { toMarkdown, writeReport };
